<?php

namespace Atom\Tools;

class ToolManager
{
    private array $tools = [];
    private ToolRegistry $registry;
    /** @var callable|null */
    private $approvalProvider = null;

    public function __construct(?ToolRegistry $registry = null)
    {
        $this->registry = $registry ?? new ToolRegistry();
    }

    public function getRegistry(): ToolRegistry
    {
        return $this->registry;
    }

    /**
     * Installs a trusted application-side approval callback for one action at a time.
     * Without a callback, execution fails closed. Approval is never inferred from
     * tool arguments generated by the model.
     */
    public function setApprovalProvider(?callable $approvalProvider): void
    {
        $this->approvalProvider = $approvalProvider;
    }

    public function hasApprovalProvider(): bool
    {
        return $this->approvalProvider !== null;
    }

    /**
     * Registers a tool.
     */
    public function registerTool(ToolInterface $tool, ?ToolDefinition $definition = null): void
    {
        $this->tools[$tool->getName()] = $tool;
        $this->registry->registerTool($tool, $definition);
    }

    /**
     * Checks if tool exists.
     */
    public function hasTool(string $name): bool
    {
        return $this->registry->hasTool($name);
    }

    /**
     * Executes the registered tool by name following full lifecycle security checks.
     */
    public function executeTool(string $name, array $arguments): array
    {
        if (!$this->hasTool($name)) {
            return [
                'success' => false,
                'error'   => "Requested tool '{$name}' is not registered."
            ];
        }

        if (!$this->registry->isEnabled($name)) {
            return [
                'success' => false,
                'error'   => "Tool '{$name}' is currently disabled by administrator policy."
            ];
        }

        // 1. Schema Validation
        $validation = $this->registry->validateInput($name, $arguments);
        if (!$validation['valid']) {
            return [
                'success' => false,
                'error'   => "Schema validation failed: " . $validation['error']
            ];
        }

        // Every tool action requires an application-side, one-action approval.
        $def = $this->registry->getDefinition($name);
        if (!$this->authorizeAction($name, $arguments, $def)) {
            return [
                'success' => false,
                'requires_human_gate' => true,
                'tool_name' => $name,
                'risk_level' => $def?->riskLevel ?? 'unknown',
                'approval_explanation' => $this->describeAction($name, $arguments, $def),
                'error' => "Tool '{$name}' requires explicit application-side human approval before execution."
            ];
        }

        // 3. Execution
        $handler = $this->registry->getHandler($name) ?? ($this->tools[$name] ?? null);
        if ($handler === null) {
            return [
                'success' => false,
                'error'   => "No handler found for tool '{$name}'."
            ];
        }

        try {
            return $handler->execute($arguments);
        } catch (\Throwable $e) {
            return [
                'success' => false,
                'error'   => "Tool execution error: " . $e->getMessage()
            ];
        }
    }

    /**
     * Authorizes a registered or delegated action. Unclassified actions are
     * still gated, and no session grant or model argument can approve them.
     */
    public function authorizeAction(string $name, array $arguments, ?ToolDefinition $definition = null): bool
    {
        if ($this->approvalProvider === null) {
            return false;
        }

        try {
            return (bool)($this->approvalProvider)($name, $arguments, $definition);
        } catch (\Throwable) {
            return false;
        }
    }

    /** Produce a bounded, redacted summary for the human approval prompt. */
    public function describeAction(string $name, array $arguments, ?ToolDefinition $definition = null): array
    {
        $redacted = (new \Atom\Security\SecretRedactor())->redact(json_encode($arguments, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE) ?: '{}');
        if (strlen($redacted) > 1200) {
            $redacted = substr($redacted, 0, 1200) . '…';
        }

        return [
            'action' => $name,
            'target' => $arguments['target'] ?? $arguments['path'] ?? $arguments['file'] ?? $arguments['url'] ?? $arguments['app'] ?? $arguments['service'] ?? $arguments['pid'] ?? 'See parameters',
            'purpose' => $definition?->description ?? "Run tool {$name}",
            'access' => $definition?->permission ?? 'tool.execute (unclassified)',
            'external_data_sharing' => $name === 'mylife_os' ? 'Personal MyLife data may be sent to the configured AI provider or fallback provider.' : 'No external sharing is known from the registered tool metadata.',
            'consequences' => $definition?->riskLevel ?? 'unclassified; approval required',
            'parameters' => $redacted,
        ];
    }

    /**
     * Lists registered tools for context builder schemas.
     */
    public function getToolsList(): array
    {
        $list = [];
        foreach ($this->tools as $name => $tool) {
            $def = $this->registry->getDefinition($name);
            $desc = $def ? $def->description : $this->getToolDescription($name);
            $list[] = [
                'name'        => $name,
                'description' => $desc,
                'risk_level'  => $def ? $def->riskLevel : 'low',
                'schema'      => $def ? $def->inputSchema : []
            ];
        }
        return $list;
    }

    private function getToolDescription(string $name): string
    {
        switch ($name) {
            case 'read_file':
                return 'Reads text files inside the workspace. Arguments: {"file_path": "relative/path/to/file.php"}';
            case 'search_code':
                return 'Searches code content/filenames inside the workspace. Arguments: {"query": "string_to_search"}';
            case 'php_lint':
                return 'Checks syntax of a PHP file. Arguments: {"file_path": "relative/path/to/file.php"}';
            case 'create_file':
                return 'Creates a new file in workspace. Arguments: {"file_path": "relative/path/to/file.php", "content": "text"}';
            case 'patch_file':
                return 'Searches and replaces code inside a file. Arguments: {"file_path": "relative/path/to/file.php", "target_content": "old_code", "replacement_content": "new_code", "interactive": true}';
            default:
                return 'Custom tool execution.';
        }
    }
}
